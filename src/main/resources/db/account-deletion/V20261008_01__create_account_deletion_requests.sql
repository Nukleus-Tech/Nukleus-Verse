BEGIN;
SET LOCAL lock_timeout = '5s';
SET LOCAL statement_timeout = '60s';

CREATE TABLE account_deletion_requests (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint REFERENCES users(id) ON DELETE SET NULL,
    requested_at timestamptz NOT NULL,
    scheduled_deletion_at timestamptz NOT NULL,
    status varchar(20) NOT NULL,
    completed_at timestamptz,
    cancelled_at timestamptz,
    retry_count integer NOT NULL DEFAULT 0,
    last_error varchar(80),
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL,
    next_attempt_at timestamptz,
    claim_token uuid,
    CONSTRAINT account_deletion_status_check
        CHECK (status IN ('PENDING','CANCELLED','PROCESSING','COMPLETED','FAILED')),
    CONSTRAINT account_deletion_retry_check CHECK (retry_count >= 0),
    CONSTRAINT account_deletion_deadline_check CHECK (scheduled_deletion_at >= requested_at),
    CONSTRAINT account_deletion_completion_check
        CHECK (status <> 'COMPLETED' OR (completed_at IS NOT NULL AND user_id IS NULL)),
    CONSTRAINT account_deletion_cancel_check
        CHECK (status <> 'CANCELLED' OR cancelled_at IS NOT NULL),
    CONSTRAINT account_deletion_claim_check
        CHECK ((status = 'PROCESSING') = (claim_token IS NOT NULL))
);

CREATE UNIQUE INDEX account_deletion_one_active_user
    ON account_deletion_requests(user_id)
    WHERE user_id IS NOT NULL AND status IN ('PENDING','PROCESSING','FAILED');
CREATE INDEX account_deletion_due
    ON account_deletion_requests(scheduled_deletion_at, id)
    WHERE user_id IS NOT NULL AND status IN ('PENDING','PROCESSING','FAILED');
CREATE INDEX account_deletion_user_history
    ON account_deletion_requests(user_id, requested_at DESC, id DESC)
    WHERE user_id IS NOT NULL;
COMMENT ON TABLE account_deletion_requests IS
    'Deletion lifecycle; manual migration; no email, URLs, tokens, provider IDs or raw errors retained.';
COMMIT;
